import Foundation

nonisolated enum GeminiPrompts: Sendable {

    // MARK: - 2-호출(병렬) 프롬프트
    //
    // 왜 한 프롬프트를 둘로 나눴나:
    //   Gemini는 google_search(웹검색 그라운딩)와 responseMimeType=application/json(JSON 강제)을
    //   '동시에' 쓸 수 없다. 두 작업은 필요한 모드가 정반대다.
    //     - 질문 생성  : 책 고유 내용을 알아야 질문이 좋다 → 그라운딩 ON  (JSON 강제 불가 → 번호줄 텍스트)
    //     - 조명·음악  : HSB·카테고리 같은 정형 데이터        → 그라운딩 OFF (JSON 강제 가능)
    //   그래서 프롬프트도 questions / lightingAndMusic 둘로 분리하고, 호출부에서 병렬 실행한다.

    // MARK: 공통 — 연령별 질문 기준표 (질문 품질의 핵심)

    /// 모든 나이 공통 말투 규칙. 나이에 따라 변하는 건 '질문의 깊이·내용'이지 '말투'가 아니다.
    private static let toneRule = """
    ## 공통 말투 규칙 (모든 나이 동일 — 절대 변하지 않음)
    - 잠자리에서 부모가 아이에게 다정하게 속삭이듯 묻는 친근한 반말 구어체: "~했어?", "~었을까?", "~면 어떨 것 같아?", "~기억나?"
    - 금지: 시험·교과서 말투("~했나요?", "~인가요?", "~말해 보세요"), 딱딱한 존댓말.
    - 나이가 어려도 말투는 똑같이 따뜻하게. 나이에 따라 변하는 건 질문의 '깊이·내용'일 뿐 '말투'가 아니다.
    """

    /// 연령별 질문 기준표(한국 아동 발달 기준 — Bloom 인지단계 · CROWD 질문기법 · Distancing 자기연결).
    private static func ageBandTable(age: Int) -> String {
        toneRule + """


        ## 연령별 질문 기준표 (\(age)세가 속한 구간을 따를 것 — 한국 아동 실제 발달 기준)
        | 구간 | 인지 깊이(Bloom) | 질문 형식(CROWD) | 자기연결(Distancing) | 취침 전 보정 |
        | 3~4세 | 기억·이해 | C(완성)·W(누구/무엇/어디) + 낮은 수준의 O(개방) | 직관적 연결("우리 집에 있는 거랑 똑같네?") | 정서적 안정 위주, 색·형태 집착 유도 금지 |
        | 5~6세 | 이해·적용·일부 분석 | W(왜/어떻게)·R(회상)·D(가벼운 경험 연결) | 감정/상황 연결("속상했던 적 있어?") | 1단계 추론만(생각하다 잠 깨지 않게) |
        | 7~8세 이상 | 분석·평가·창조 | O(개방)·D(본격 가상/현실 연결)·다단계 R | 가치/행동 연결("너라면 어떤 선택을 했을까?") | 갈등 비판은 하되 마지막은 용서·화해·수용으로 마무리 |
        예시) 3~4세 "두꺼비가 뭘 들고 있어?" / 5~6세 "두꺼비가 왜 콩쥐를 도와줬을까? 너도 속상했던 적 있어?" / 7~8세+ "팥쥐가 벌 받은 게 정말 공정하다고 생각해?"
        → \(age)세에 맞는 칸의 깊이·형식으로 질문 3개. 말투는 위 공통 규칙을 모든 나이에 동일 적용.
        """
    }

    // MARK: 호출 A — 질문 생성 (그라운딩 ON, 번호줄 텍스트 출력)

    /// 책을 웹검색으로 조사해 연령 맞춤 질문 3개를 만든다.
    /// 그라운딩과 JSON 강제는 동시 사용 불가 → 출력은 "1) 2) 3)" 번호줄 텍스트로 받아 정규식 파싱한다.
    static func questions(bookTitle: String, isbn: String, age: Int, bookDescription: String) -> String {
        """
        너는 아동 독서교육 전문가야. 구글 검색을 적극 사용해 책 『\(bookTitle)』(ISBN \(isbn))의 구체적 내용을 조사하라.
        \(ageBandTable(age: age))

        검색으로 알아낸 이 책 고유 내용 기반으로 \(age)세 맞춤 질문 3개를 만들어라.

        ## 질문 작성 규칙 (반드시)
        - 2문장 이내로 짧게 써라.
        - 줄거리·상황 배경설명을 질문 앞에 깔지 말고 핵심만 바로 물어라.
        - 나쁜 예: "콩쥐가 새어머니에게 구박받으며 슬퍼할 때, 두꺼비가 나타나 왜 도와줬을까?"
        - 좋은 예: "두꺼비는 왜 콩쥐를 도와줬을까? 너도 누구 도와준 적 있어?"

        참고용 짧은 줄거리: \(bookDescription)

        ## 효과(effect) 작성 규칙 (반드시)
        - 각 질문이 아이에게 길러주는 능력을 '두 단어 이내'의 짧은 명사구로 끊어 써라.
        - 좋은 예: "창의력 증진", "공감 능력", "상상력 자극", "문제 해결력"
        - 문장으로 길게 풀지 마라. (나쁜 예: "타인의 입장에서 생각하는 공감 능력을 길러줍니다")

        ## 출력 형식 (반드시)
        질문 3개만 출력해라. 각 줄을 다음 형식으로 써라: 번호) 질문 || 효과
        예: 1) 두꺼비는 왜 콩쥐를 도와줬을까? 너도 누구 도와준 적 있어? || 공감 능력
        인사말·설명·줄거리 요약 등 다른 문장은 절대 쓰지 마라.
        """
    }

    // MARK: 호출 B — 조명·음악 선정 (그라운딩 OFF + JSON 강제)

    /// 책 분위기에 맞는 조명(hue 자유 / 밝기·채도는 수면 유도 고정 범위)과 음악 카테고리를 JSON으로 받는다.
    static func lightingAndMusic(bookTitle: String, bookDescription: String) -> String {
        """
        너는 취침 전 독서 환경 설계 전문가야.
        책 정보 — 제목: \(bookTitle) / 줄거리: \(bookDescription)

        조명을 정하라:
        - 색상(hue): 책의 분위기·핵심 정서·표지 느낌과 가장 어울리게 자유롭게 정해라. (색 제한 없음)
        - 밝기(brightness): '수면 유도' 고정 기준 → 10~30. 취침 직전 멜라토닌 분비를 위해 촛불처럼 어둑하게.
        - 채도(saturation): '수면 유도' 고정 기준 → 40~70. 포근하되 자극적이지 않게.

        음악: 차분하고 느린 템포만. 책의 분위기·핵심 정서에 가장 어울리는 무드 하나를 아래에서 골라라.
        musicCategory는 다음 12개 중 하나의 '영문 토큰'으로만 답하라(설명 문구 말고 토큰만):
        \(MusicCategory.promptList)

        JSON으로만 답하라: { "lighting": {"hue": 0~360 정수, "saturation": 0~100 정수, "brightness": 0~100 정수}, "musicCategory": "Warm 등 12개 토큰 중 하나" }
        """
    }

}
